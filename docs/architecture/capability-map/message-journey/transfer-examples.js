/* Fictional examples for existing guided transfers, never an additional runtime pipeline. */
(function (global) {
  'use strict';

  function create(data) {
    const user = data.current_user, fact = data.existing_fact;
    const proposal = data.review_decision.proposals[0];
    const persona = `${data.persona.name}, version ${data.persona.version}`;
    const message = ['Message ID (this text, not its author)', user.id];
    const run = ['Run ID (processing job for this turn)', data.run_id];
    const location = ['Stored location fact', `${fact.value}, version ${fact.version}; fact ID: ${fact.fact_id}`];
    const correction = `${fact.value} (v${fact.version}) -> ${proposal.value} (v${fact.version + 1})`;
    const lesson = (action, input, output, note, edges) => ({action, input, output, note, edges});
    return {
      submit: lesson('Submit Alex\'s message',
        [['Alex\'s complete message', user.content]],
        [['Acceptance input', 'The same text, with a duplicate-request key and execution limits.']],
        'ADE checks whether it can accept the turn. Nothing here is a generated reply or an accepted location fact.'),
      'accepted-source': lesson('Capture the exact message and link it to this turn',
        [['Original user message', user.content], ['Speaker', `${data.subject} (user in this conversation)`]],
        [message, run, ['Linked source', `${user.id} belongs to the conversation and to processing job ${data.run_id}. The text is unchanged.`]],
        'This is source bookkeeping, not memory extraction. The next grouped arrows illustrate saving the message and job together; these are not separate service calls.'),
      'save-user': lesson('Save the message and pending job together',
        [['Original user message', user.content], message, run],
        [['Saved message', `${user.id}: exact original text, role=user, linked to run ${data.run_id}.`],
          ['Saved processing job', `${data.run_id}: pending, with its lease and acceptance events.`]],
        'Both records become visible in one database transaction. The stored location remains Ottawa; no assistant reply exists yet.',
        ['save-user', 'save-accepted-run']),
      'accepted-receipt': lesson('Return a receipt so the interface can track the job',
        [run, ['Job status', 'Pending; message and job have been saved.']],
        [['Receipt shown to the interface', `Run ID: ${data.run_id}. Acceptance confirmed; monitor this job for an outcome.`]],
        'A receipt acknowledges acceptance. It is not Rowan\'s answer, and it does not mean processing has finished.'),
      'claim-run': lesson('Let a worker claim the queued job',
        [run, ['Before', 'Pending; waiting to be processed.']],
        [['After', `${data.run_id}: running. A worker starts an execution attempt while holding the lease.`]],
        'A lease is time-limited exclusive permission to work on this turn. A retry can create another attempt of the same run; it does not create another user message.'),
      'bound-definition': lesson('Load the character version already bound to this conversation',
        [['Existing conversation binding', persona]],
        [['Attempt uses', `${persona}: ${data.persona.intent}`]],
        'ADE reads the existing persona, prompt, model deployment and memory policy. It does not author a new persona for this message.'),
      'eligible-scope': lesson('Limit memory access to the correct subject',
        [['Current user message', user.content], ['Memory subject', `${data.subject}; subject ID: ${data.subject_id}`]],
        [['Eligible evidence', 'Local conversation messages and facts belonging to Alex within this workspace.']],
        'The subject ID identifies whose profile facts these are. This fictional typed-policy path does not retrieve older conversations or another character\'s shared experiences.'),
      'fact-query': lesson('Ask for relevant stored facts',
        [['Current user message', user.content], ['Eligible subject', data.subject]],
        [['Search request', 'Look for facts relevant to Alex\'s current message, within the allowed subject scope.']],
        'The detailed view includes query-vector preparation and matching. This example does not invent the exact generated search query or numeric vector.'),
      'base-context': lesson('Bring local conversation evidence into context construction',
        [['Previous user message', data.previous_user.content], ['Current user message', user.content]],
        [['Local evidence available for the reply', 'The presentation is tomorrow; the slides are finished; Alex has not rehearsed.']],
        'These are readable excerpts of the local context, not newly accepted facts. No new summary is prepared in this example.'),
      'fact-results': lesson('Add the retrieved fact without hiding the new statement',
        [location, ['Current user statement', proposal.evidence_quote]],
        [['Evidence available together', `Stored fact: ${fact.value}, version ${fact.version}. New message: Alex says they moved to ${proposal.value}.`]],
        'Retrieval does not update the fact. The model can see both the stored value and the newer statement; review and commit happen later.'),
      'delivered-request': lesson('Bind the actual conversation request',
        [['Character', `${persona}: ${data.persona.intent}`], ['Evidence', 'Current message, local presentation history, and the retrieved location fact.']],
        [['Conversation input', `${persona}; message ID: ${user.id}; presentation tomorrow; stored location ${fact.value}, version ${fact.version}.`]],
        'ADE fits and binds the actual request. A request fitting the input limit does not prove its evidence is sufficient or correctly interpreted.'),
      'generation-input': lesson('Use the persona and evidence to generate a response',
        [['Intended character', data.persona.intent], ['Situation', 'Slides finished, no rehearsal; local chat says the talk is tomorrow.']],
        [['Generation input', `The bound character specification, Alex\'s message (${user.id}), and the supplied evidence.`]],
        'Interpretation, conversational choice and expression share one model call. This action has not produced a candidate yet.'),
      'candidate-reply': lesson('Receive a candidate reply',
        [['Generation input', 'The character specification and the supplied conversation evidence.']],
        [['Candidate reply', data.candidate_reply]],
        'This is one fictional possible response, not measured model output or a gold standard. It is not saved or shown to Alex yet.'),
      'typed-review-input': lesson('Give the typed reviewer user evidence and existing facts',
        [['Current user evidence', proposal.evidence_quote], message, location],
        [['Typed review input', 'Current user message, up to eight prior user messages, active facts and entities.']],
        'The typed reviewer does NOT receive the candidate reply. Its task is to propose supported fact changes, not to approve Rowan\'s prose.'),
      'index-input': lesson('Prepare a search representation for the proposed correction',
        [['Reviewer proposal', `Correct fact ID ${fact.fact_id} to ${proposal.value}; expect existing version ${proposal.expected_version}.`],
          ['Quoted user evidence', proposal.evidence_quote]],
        [['Fact document for embedding', `${data.subject}: current location ${proposal.value}.`]],
        'The omitted review call has returned this fictional proposal. ADE prepares its structure and a representation; the stored location still has not changed.'),
      'proposed-changes': lesson('Pass the proposed fact correction to finalization',
        [['Prepared proposal', `Fact ID: ${fact.fact_id}; expected version: ${proposal.expected_version}; new value: ${proposal.value}.`],
          ['Source message ID and quote', `${user.id}: "${proposal.evidence_quote}"`]],
        [['Pending change', correction]],
        'This is a proposal, not committed memory. Source and schema checks do not prove that the reviewer interpreted the statement correctly.'),
      'prepared-index': lesson('Hold the matching vector ready for the same commit',
        [['Proposed new fact value', `${data.subject}: current location ${proposal.value}.`]],
        [['Prepared search representation', 'A vector tied to the proposed fact revision and the configured embedding space.']],
        'The detailed view includes the embedding call. No numeric vector is fabricated here, and the representation is not saved separately ahead of the fact.'),
      'pending-reply': lesson('Check the pending reply and changes before writing success',
        [['Candidate reply', data.candidate_reply], ['Pending correction', correction], ['Prepared representation', 'Matching vector for the proposed new location.']],
        [['Finalization input', 'Reply, proposal and representation; recheck cancellation, lease, versions and source links.']],
        'All of this is still pending. A failed guard prevents this attempt from writing the successful reply-and-memory bundle.'),
      'commit-dialogue': lesson('Commit the reply, fact change and success together',
        [['Pending bundle', 'Candidate reply, proposed correction, prepared vector and run outcome.']],
        [['Saved assistant reply', data.candidate_reply], ['Saved fact change', correction], ['Saved job outcome', `${data.run_id}: succeeded; lease released.`]],
        'This assumes all guards pass. The displayed dialogue arrow is only one part of the same atomic transaction: reply, fact, index and success are saved together. No new summary is saved.'),
      'committed-outcome': lesson('Report the committed job outcome',
        [run, ['Database result', 'The successful reply-and-memory transaction has committed.']],
        [['Runtime outcome', `${data.run_id}: succeeded. The reply and permitted changes are persisted.`]],
        'Success is reported after commit, not merely because generation returned text. The interface still needs to reload the persisted result.'),
      'refresh-ui': lesson('Reload the saved reply into the conversation',
        [run, ['Persisted outcome', 'Succeeded; assistant reply is saved.']],
        [['Reply Alex sees', data.candidate_reply]],
        'Events and status polling prompt a reload. This is the same saved candidate text, not an early stream directly from the generation call.'),
      'lineage-state': lesson('Show where the saved fact change came from',
        [['Committed fact', `${proposal.value}, version ${fact.version + 1}; fact ID: ${fact.fact_id}`]],
        [['Lineage display', `${correction}; source message ID: ${user.id}; quote: "${proposal.evidence_quote}"`]],
        'Lineage links the accepted change to Alex\'s original user message, not to Rowan\'s candidate reply.'),
      'activity-state': lesson('Display the retained processing status',
        [run, ['Retained metadata', 'Succeeded status and available processing events.']],
        [['Activity display', `Run ID: ${data.run_id}; status: succeeded.`]],
        'Public activity can be incomplete and can appear earlier. It is not hidden reasoning or a full record of every input packet.'),
    };
  }

  global.AdeJourneyTransferExample = {create};
})(globalThis);
